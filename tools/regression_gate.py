def run(corpus=None):
    """`(rows, status)` -- every entry checked, and the exit code to use."""
    rows, status = [], 0
    for item in corpus if corpus is not None else CORPUS:
        try:
            finding = item.check()
        except Unreadable as e:
            rows.append((item, "UNREADABLE", str(e)))
            status = max(status, 1)
            continue
        except Exception as e:  # a check that crashes has not said the failure is fixed
            rows.append((item, "UNREADABLE", f"the check itself raised {type(e).__name__}: {e}"))
            status = max(status, 1)
            continue
        if finding:
            rows.append((item, "REGRESSED", finding))
            status = 2
        else:
            rows.append((item, "held", ""))
    return rows, status


def format_report(rows, status):
    lines = []
    for item, verdict, detail in rows:
        if verdict == "held":
            lines.append(f"held        {item.slug}  (cycle {item.cycle}, {item.date}; {item.surface})")
        else:
            lines.append(f"{verdict}  {item.slug}  (cycle {item.cycle}, {item.date}; {item.surface})")
            lines.append(f"      what went wrong then: {item.failure}")
            lines.append(f"      what I see now: {detail}")
    lines.append(f"Checked {len(rows)} past failure(s) from this loop's own journal.")
    if status == 2:
        lines.append("A failure this loop already paid for once is back. Do not merge over this.")
    elif status == 1:
        lines.append("At least one check could not read what it needs, so this is not a clean run.")
    else:
        lines.append("Every past failure in the corpus is still fixed.")
    return "\n".join(lines)


def main(argv=None):
    rows, status = run()
    print(format_report(rows, status))
    return status


if __name__ == "__main__":
    raise SystemExit(main())
