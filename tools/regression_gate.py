def _check_digest_roll_reads_the_whole_document() -> Optional[str]:
    """A spliced live digest must be refused before the roll, not after.

    Cycle 492 wrote `journal-digest.md` carrying two `## Needs input` and two
    `## Next cycle` sections, one block stacked under the other.
    `tools.roll_digest` read those exact bytes out of the vault seconds later
    and said nothing, because every check it carries reasons about the
    `## Digest` section `plan` splits out and the damage was above it. The
    site hid it too -- `parse_digest` keeps the last section of each name --
    so the only reader who saw it was the owner, in Obsidian.
    """
    from tools import roll_digest
    from tools.rolling import RollError

    head = "---\ntype: log\n---\n\n# Journal — Digest\n"
    tail = "\n## Digest\n\n**Cycle 2** (2026-08-26 19:14) — Second.\n\n**Cycle 1** (2026-08-26 18:36) — First.\n"
    spliced = head + "\n## Next cycle\n\nStale.\n\n## Next cycle\n\nCurrent.\n" + tail
    whole = head + "\n## Next cycle\n\nOnly one.\n" + tail

    try:
        roll_digest.plan(spliced, "", keep=1)
    except RollError as exc:
        if "duplicated heading" not in str(exc):
            return f"roll_digest refused a spliced digest for the wrong reason: {exc}"
    else:
        return "roll_digest rolled a digest holding two '## Next cycle' sections"

    # Two-sided: a checker that refuses everything would pass the half above
    # while making every honest digest unrollable.
    try:
        roll_digest.plan(whole, "", keep=1)
    except RollError as exc:
        return f"roll_digest refused an undamaged digest: {exc}"
    return None


def _check_ci_health_ignores_an_abandoned_run() -> Optional[str]:
    """A queued run that later runs have overtaken must not read as a live stall.

    Measured Cycle 495, 2026-08-26 20:04 Oslo: run 32984347949 was created four
    seconds into that afternoon's Actions outage and was still `queued` with
    zero jobs three hours later — three minutes after githubstatus resolved the
    incident, with its own pull request merged and eight later runs in the same
    repo finished. `ci_health` read `operational` off the status page and still
    said a merge could not complete, off that orphan alone. Nothing removes an
    abandoned run from a queue, so that verdict had no end date.
    """
    import json
    import subprocess
    from tools import ci_health

    class _Resp:
        def __init__(self, body):
            self._body = body.encode()

        def read(self):
            return self._body

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

    def opener(request, timeout=None):
        return _Resp(json.dumps({
            "components": [{"name": "Actions", "status": "operational"}],
            "incidents": []}))

    def gh_with_completed_at(stamp):
        def gh(cmd, **kwargs):
            path = cmd[2]
            if "/jobs" in path:
                return subprocess.CompletedProcess(cmd, 0, stdout="0", stderr="")
            if "status=completed" in path:
                body = [] if stamp is None else [{"id": 2, "created_at": stamp}]
                return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps(body), stderr="")
            if "/commits" in path:
                return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps([]), stderr="")
            return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps([{
                "id": 1, "name": "build", "status": "queued", "head_branch": "b",
                "created_at": "2000-01-01T00:00:00Z"}]), stderr="")
        return gh

    status, lines = ci_health.check(opener=opener,
                                    run=gh_with_completed_at("2000-01-01T01:00:00Z"),
                                    repos=["Org/repo"])
    if status != 0 or not any(l.startswith("ABANDONED") for l in lines):
        return ("ci_health called a merge impossible on a queued run that a later run had "
                f"already overtaken (exit {status}) -- an orphan from an outage that has since "
                "resolved would have refused every merge after it, forever")

    # Two-sided: with nothing completed after it, the stall must still stand,
    # or the check above only proves the tool stopped reporting stalls at all.
    status, lines = ci_health.check(opener=opener, run=gh_with_completed_at(None),
                                    repos=["Org/repo"])
    if status != 2 or not any(l.startswith("STALLED") for l in lines):
        return ("ci_health quietened a zero-job run with no completed run after it to "
                f"compare against (exit {status}) -- nothing measured, nothing to quieten")
    return None


def _check_ci_health_separates_the_two_causes() -> Optional[str]:
    """A GitHub-side outage and a run of ours creating no jobs must stay two lines.

    Cycle 487 read a run queued fourteen minutes with zero jobs as the Actions
    billing block, because that is the failure this loop remembers. It was a
    GitHub-side outage opened four seconds after the run was created, and the
    two have opposite conclusions -- "wait, then merge" against "nothing merges
    until September and the owner has to act".
    """
    import json
    import subprocess
    import urllib.error
    from tools import ci_health

    class _Resp:
        def __init__(self, body):
            self._body = body.encode()

        def read(self):
            return self._body

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

    def opener_for(actions):
        def opener(request, timeout=None):
            return _Resp(json.dumps({
                "components": [{"name": "Actions", "status": actions}],
                "incidents": [{"name": "Incident with Actions"}] if actions != "operational" else [],
            }))
        return opener

    def gh(cmd, **kwargs):
        path = cmd[2]
        if "/jobs" in path:
            return subprocess.CompletedProcess(cmd, 0, stdout="0", stderr="")
        return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps([{
            "id": 1, "name": "build", "status": "queued", "head_branch": "b",
            "created_at": "2000-01-01T00:00:00Z"}]), stderr="")

    status, lines = ci_health.check(opener=opener_for("major_outage"), run=gh,
                                    repos=["Org/repo"])
    github_side = [l for l in lines if l.startswith("GITHUB-SIDE")]
    stalled = [l for l in lines if l.startswith("STALLED")]
    if status != 2 or len(github_side) != 1 or len(stalled) != 1:
        return ("ci_health merged the GitHub-side outage and the zero-job run into one "
                f"verdict (exit {status}, {len(github_side)} outage line(s), "
                f"{len(stalled)} stalled line(s)) -- Cycle 487 chased the wrong cause")

    # Two-sided: with GitHub healthy the stalled line must survive on its own,
    # or the check above is only reading the status page.
    status, lines = ci_health.check(opener=opener_for("operational"), run=gh,
                                    repos=["Org/repo"])
    if status != 2 or not any(l.startswith("STALLED") for l in lines):
        return ("ci_health stopped reporting a run of ours that created zero jobs once "
                f"githubstatus said Actions was operational (exit {status}) -- that is the "
                "billing-block shape, which githubstatus never reports")
    return None


def _check_name_guard_sees_an_unstaged_file() -> Optional[str]:
    """The owner's-name guard must read the files a commit will carry, not only the tracked ones.

    Cycle 488 added `tools/ci_health.py` with his name in its opening
    docstring, ran the suite before committing, and recorded "green locally"
    honestly. The suite really was green: the guard built its file list from
    `git ls-files`, which lists only what is *already tracked*, so the one new
    module it needed to read was the one file it could not see. CI staged it
    and turned red. That is a positive result guaranteed in advance, aimed
    precisely at the case the guard exists for.

    Two-sided on purpose: an unstaged file must be in the list, and an ignored
    one must not -- a version that returned every path on the disk would pass
    the first half and drag `node_modules` in behind it.
    """
    from tools import name_scan

    root = Path(__file__).resolve().parent.parent
    probe = root / "_regression_gate_unstaged_probe.py"
    ignored = root / "__pycache__" / "_regression_gate_ignored_probe.py"
    ignored.parent.mkdir(exist_ok=True)
    probe.write_text('"""Edvard wrote this and never staged it."""\n')
    ignored.write_text('"""Edvard, in a path .gitignore covers."""\n')
    try:
        try:
            files = name_scan.repo_files(root)
        except Exception as exc:  # noqa: BLE001 -- an unreadable tree is a failure here
            return f"could not list the working tree: {exc}"
        if probe.name not in files:
            return "a file that is not staged yet is invisible to the name guard"
        if f"__pycache__/{ignored.name}" in files:
            return "the name guard is reading files git is told to ignore"
        if not name_scan.scan([str(probe)]):
            return "the scan does not flag the owner's name in an unstaged docstring"
    finally:
        probe.unlink()
        ignored.unlink()
    return None


