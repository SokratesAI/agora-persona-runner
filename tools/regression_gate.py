def _check_unattended_metered() -> Optional[str]:
    from agora_runner import reply as reply_mod

    persona = {"model": "anthropic:claude-sonnet-5", "thinking": False}
    history = [{"role": "user", "content": "hi"}]

    try:
        reply_mod.generate_reply(persona, {}, "s", history, "conv-1", unattended=True)
    except reply_mod.MeteredProviderBlocked:
        pass
    except Exception as e:
        return (f"an unattended turn on 'anthropic:' raised {type(e).__name__} instead of "
                f"MeteredProviderBlocked ({e}) -- the guard is not the thing refusing it")
    else:
        return "an unattended turn on a metered provider was allowed through"

    # The other side: the guard must not be refusing everything. The same
    # unattended turn on the subscription provider has to reach the model.
    # Stubbed rather than really dispatched -- a check that phones a model to
    # prove a guard let it through is a check nobody will run every cycle.
    original = reply_mod.claude_cli_generate
    reached = []
    try:
        reply_mod.claude_cli_generate = lambda *a, **k: reached.append(a)
        reply_mod.generate_reply(dict(persona, model="claude-cli:claude-sonnet-5"), {}, "s",
                                 history, "conv-1", unattended=True)
    except reply_mod.MeteredProviderBlocked:
        return ("the guard also refuses 'claude-cli:', which is the subscription provider -- "
                "it would block every unattended turn, so its refusal proves nothing")
    except Exception as e:
        return f"the subscription path raised {type(e).__name__} before reaching the model: {e}"
    finally:
        reply_mod.claude_cli_generate = original
    if not reached:
        return ("an unattended subscription turn never reached the model, so the refusal above "
                "is refusing something other than the metered provider")
    return None


